"""Application Data Transfer Objects for strategic intelligence and AI."""

from __future__ import annotations

from dataclasses import dataclass
from uuid import UUID

from src.indicators.application.dto import PeriodIndicatorsDTO
from src.indicators.domain.services.simulator import CostCenterImpact
from src.intelligence.domain.models import (
    AllocationAnomaly,
    AnomalySeverity,
    AnomalyType,
)
from src.shared.domain.value_objects import Period


@dataclass(frozen=True, slots=True)
class AnomalyDTO:
    """DTO representing an identified cost allocation anomaly."""

    measurement_id: UUID
    contract_id: UUID
    cost_center_id: UUID
    anomaly_type: AnomalyType
    severity: AnomalySeverity
    description: str
    baseline_percentage: str | None = None
    actual_percentage: str | None = None

    @classmethod
    def from_domain(cls, anomaly: AllocationAnomaly) -> AnomalyDTO:
        """Create AnomalyDTO from a domain entity.

        Args:
            anomaly: The source domain anomaly.

        Returns:
            AnomalyDTO: The mapped transfer object.
        """
        return cls(
            measurement_id=anomaly.measurement_id,
            contract_id=anomaly.contract_id,
            cost_center_id=anomaly.cost_center_id,
            anomaly_type=anomaly.anomaly_type,
            severity=anomaly.severity,
            description=anomaly.description,
            baseline_percentage=(
                str(anomaly.baseline_percentage)
                if anomaly.baseline_percentage
                else None
            ),
            actual_percentage=(
                str(anomaly.actual_percentage) if anomaly.actual_percentage else None
            ),
        )


@dataclass(frozen=True, slots=True)
class ExecutiveSummaryDTO:
    """Comprehensive executive period summary with deterministic and AI insights."""

    period: Period
    financial_health_status: str
    executive_summary: str
    root_causes: list[str]
    strategic_recommendations: list[str]
    anomalies: list[AnomalyDTO]
    indicators_summary: PeriodIndicatorsDTO
    is_fallback: bool = False
    ai_provider: str = "fake"


@dataclass(frozen=True, slots=True)
class ScenarioEvaluationDTO:
    """Appraisal of what-if scenario impacts generated by AI."""

    scenario_name: str
    period: Period
    strategic_feasibility: str
    key_tradeoffs: list[str]
    recommendations: list[str]
    impacts: list[CostCenterImpact]
    is_fallback: bool = False
